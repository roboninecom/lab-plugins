// Embed a published STS32XX release (release.json + encoded image) into the plugin bundle.
//
//   node plugins/robonine/servo-firmware/scripts/embedRelease.mjs <release.json> <module-name>
//
// Writes src/releases/<module-name>.ts. The image's size and SHA-256 are checked against
// the manifest here and again at runtime (loadRelease) before any servo is touched.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const [manifestPath, name] = process.argv.slice(2)

if (!manifestPath || !/^[a-z0-9-]+$/.test(name ?? '')) {
  console.error('usage: embedRelease.mjs <release.json> <module-name>')
  process.exit(1)
}

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))

if (typeof manifest.image !== 'string' || /[/\\:]/.test(manifest.image) || manifest.image === '.' || manifest.image === '..') {
  throw new Error('Image must be a filename next to the manifest')
}

const image = readFileSync(join(dirname(resolve(manifestPath)), manifest.image))
const digest = createHash('sha256').update(image).digest('hex')

if (image.length !== manifest.size || digest !== manifest.sha256) {
  throw new Error(`Image does not match the manifest (size ${image.length}, sha256 ${digest})`)
}

const outDir = join(dirname(fileURLToPath(import.meta.url)), '../src/releases')

mkdirSync(outDir, { recursive: true })
writeFileSync(
  join(outDir, `${name}.ts`),
  `// Generated by scripts/embedRelease.mjs from ${manifest.release} — do not edit.\n` +
    `import type { ReleaseManifest } from '../firmware/release'\n\n` +
    `export const manifest: ReleaseManifest = ${JSON.stringify(manifest)}\n\n` +
    `export const imageBase64 = '${image.toString('base64')}'\n`,
)
console.log(`${name}: ${manifest.release}, ${image.length} bytes, sha256 ${digest}`)
